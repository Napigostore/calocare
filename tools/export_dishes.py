"""Exports the app's built-in foods (FoodDb.kt) to server/src/dishes.ts: names and nutrition.

The AI server shows the names to the model so it answers with dishes the app's food table knows,
and uses the nutrition to judge whether a correction sent by a user is plausible.
Run again after editing FoodDb.kt, then redeploy the server:

    python tools/export_dishes.py
"""
import io
import json
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), '..')
SRC = os.path.join(ROOT, 'app/src/main/java/com/calocare/app/data/FoodDb.kt')
OUT = os.path.join(ROOT, 'server/src/dishes.ts')

LINE = re.compile(
    r'f\("[^"]+", "(?P<name>[^"]+)", "[^"]*", "[^"]+", (?P<kcal>\d+), (?P<p>[\d.]+), (?P<c>[\d.]+), (?P<f>[\d.]+), [A-Z]+(?:, "(?P<tags>[^"]*)")?'
)
lines = [line for line in io.open(SRC, encoding='utf-8') if line.lstrip().startswith('f("')]
foods = []
for line in lines:
    m = LINE.search(line)
    assert m, 'unrecognised food line in FoodDb.kt: ' + line.strip()
    food = {'name': m['name'], 'kcal': int(m['kcal']), 'protein_g': float(m['p']), 'carbs_g': float(m['c']), 'fat_g': float(m['f'])}
    if 'alcohol' in (m['tags'] or '').split():
        food['alcohol'] = True
    foods.append(food)
assert len({f['name'] for f in foods}) == len(foods), 'duplicate food names in FoodDb.kt'

body = "// Generated by tools/export_dishes.py from the app's FoodDb.kt. Do not edit by hand.\n"
body += 'export interface TableFood {\n  name: string;\n  kcal: number;\n  protein_g: number;\n  carbs_g: number;\n  fat_g: number;\n  alcohol?: boolean;\n}\n\n'
body += 'export const FOODS: TableFood[] = [\n' + ''.join('  ' + json.dumps(f, ensure_ascii=False) + ',\n' for f in foods) + '];\n\n'
body += 'export const DISHES: string[] = FOODS.map((f) => f.name);\n'
io.open(OUT, 'w', encoding='utf-8', newline='\n').write(body)
print(f'{len(foods)} foods -> {os.path.relpath(OUT, ROOT)}')
