"""Generates the Play Store files that are derived from the app: the 512 px icon and the hosted privacy policy.

    python tools/store_assets.py
"""
import html
import io
import json
import math
import os
import re

from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(__file__), '..')
OUT = os.path.join(ROOT, 'play-store')
os.makedirs(OUT, exist_ok=True)


def icon(size=512, scale=4):
    """Same drawing as res/drawable/ic_launcher_fg.xml on the launcher gradient, supersampled."""
    n = size * scale
    img = Image.new('RGB', (n, n))
    px = img.load()
    a, b = (0x1F, 0x9D, 0x61), (0x7B, 0xC9, 0x6F)
    for y in range(n):
        for x in range(n):
            t = (x + y) / (2 * n)
            px[x, y] = tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
    d = ImageDraw.Draw(img, 'RGBA')
    c, r, w = n / 2, n * 0.30, n * 0.075
    box = [c - r, c - r, c + r, c + r]
    d.arc(box, 0, 360, fill=(255, 255, 255, 85), width=round(w))
    d.arc(box, -90, 160, fill=(255, 255, 255, 255), width=round(w))
    for ang in (-90, 160):  # round caps
        ex, ey = c + (r - w / 2) * math.cos(math.radians(ang)), c + (r - w / 2) * math.sin(math.radians(ang))
        d.ellipse([ex - w / 2, ey - w / 2, ex + w / 2, ey + w / 2], fill=(255, 255, 255, 255))
    # flame
    k = n / 108 * 1.25
    pts = [(54, 40), (59, 46), (63, 51), (63, 58), (60, 64), (54, 67), (48, 64), (45, 58), (46, 53), (49.5, 49), (51, 52.5), (52.5, 52), (52.3, 46)]
    d.polygon([(c + (x - 54) * k, c + (y - 54) * k) for x, y in pts], fill=(255, 183, 77, 255))
    img.resize((size, size), Image.LANCZOS).save(os.path.join(OUT, 'icon-512.png'))


def privacy():
    """Renders the in-app policy text (ui/PrivacyScreen.kt) as a page to host at the listing's privacy URL."""
    src = io.open(os.path.join(ROOT, 'app/src/main/java/com/calocare/app/ui/PrivacyScreen.kt'), encoding='utf-8').read()
    body = src[src.index('val sections'):src.index('@Composable')]
    parts = []
    for title, chunk in re.findall(r'"([^"]+)" to\n((?:\s+"(?:[^"\\]|\\.)*"(?: \+)?,?\n)+)', body):
        text = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', chunk)).replace('\\n', '\n')
        paragraphs = ''.join('<p>%s</p>' % html.escape(line) for line in text.split('\n'))
        parts.append('<h2>%s</h2>%s' % (html.escape(title), paragraphs))
    page = '''<!doctype html>
<html lang="vi"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>CaloCare – Chính sách quyền riêng tư</title>
<style>body{font:16px/1.6 system-ui,sans-serif;max-width:720px;margin:0 auto;padding:24px 16px;color:#1b1f1c}
h1{color:#1f9d61}h2{font-size:1.1rem;margin-top:1.6em}</style></head><body>
<h1>CaloCare – Chính sách quyền riêng tư</h1>
<p>Cập nhật: 16/10/2026</p>
%s
<h2>Liên hệ</h2><p>%s</p>
</body></html>
''' % ('\n'.join(parts), html.escape(re.search(r'CONTACT_EMAIL = "([^"]*)"', src).group(1) or '[ĐIỀN EMAIL HỖ TRỢ]'))
    io.open(os.path.join(OUT, 'privacy-policy.html'), 'w', encoding='utf-8', newline='\n').write(page)
    # The server serves the same page at /privacy: that is the public URL the store listings point to.
    io.open(os.path.join(ROOT, 'server/src/privacy.ts'), 'w', encoding='utf-8', newline='\n').write(
        "// Generated by tools/store_assets.py from the app's PrivacyScreen.kt. Do not edit by hand.\nexport const PRIVACY_PAGE = "
        + json.dumps(page, ensure_ascii=False) + ';\n')
    return len(parts)


icon()
print('sections:', privacy())


def feature_graphic():
    """The 1024x500 banner Google Play shows at the top of the listing."""
    from PIL import ImageFont
    w, h = 1024, 500
    img = Image.new('RGB', (w, h))
    px = img.load()
    a, b = (0x1F, 0x9D, 0x61), (0x7B, 0xC9, 0x6F)
    for y in range(h):
        for x in range(w):
            t = (x / w + y / h) / 2
            px[x, y] = tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
    logo = Image.open(os.path.join(OUT, 'icon-512.png')).resize((300, 300), Image.LANCZOS)
    mask = Image.new('L', (300, 300), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, 299, 299], radius=66, fill=255)
    img.paste(logo, (70, 100), mask)
    d = ImageDraw.Draw(img)
    # Segoe UI ships with Windows and has the Vietnamese glyphs.
    fonts = os.path.join(os.environ.get('WINDIR', 'C:/Windows'), 'Fonts')
    bold = ImageFont.truetype(os.path.join(fonts, 'segoeuib.ttf'), 92)
    regular = ImageFont.truetype(os.path.join(fonts, 'segoeui.ttf'), 33)
    d.text((420, 120), 'CaloCare', font=bold, fill='white')
    d.text((424, 250), 'Đếm calo món Việt bằng một chạm', font=regular, fill='white')
    d.text((424, 300), 'Chụp ảnh bữa ăn · Coach dinh dưỡng', font=regular, fill=(235, 250, 240))
    img.save(os.path.join(OUT, 'feature-graphic-1024x500.png'))


feature_graphic()


# Captions for the store screenshots, by the number the raw file name starts with.
CAPTIONS = {
    '01': 'Biết ngay hôm nay\nnạp và tiêu bao nhiêu calo',
    '02': 'Chạm một lần\nlà ghi xong món ăn',
    '03': 'Đưa món vào vòng tròn,\nAI tính calo giúp bạn',
    '04': 'Tổng kết bữa ăn:\ncalo, đạm, đường, muối',
    '05': 'Kết nối đồng hồ,\ntheo dõi vận động',
}


def screenshots():
    """Turns phone screenshots in play-store/raw-screenshots/ into 1080x1920 store images with a caption.

    Google Play refuses screenshots more than twice as tall as they are wide, which is what modern
    phones produce; framing them on a 9:16 canvas fixes that. The status bar and the system
    navigation bar are cropped away.
    """
    from PIL import ImageFont
    raw = os.path.join(OUT, 'raw-screenshots')
    if not os.path.isdir(raw):
        return 0
    done = os.path.join(OUT, 'screenshots')
    os.makedirs(done, exist_ok=True)
    font = ImageFont.truetype(os.path.join(os.environ.get('WINDIR', 'C:/Windows'), 'Fonts', 'segoeuib.ttf'), 58)
    w, h = 1080, 1920
    names = sorted(n for n in os.listdir(raw) if n.lower().endswith(('.jpg', '.jpeg', '.png')))
    for name in names:
        canvas = Image.new('RGB', (w, h))
        d = ImageDraw.Draw(canvas)
        a, b = (0x1F, 0x9D, 0x61), (0x7B, 0xC9, 0x6F)
        for y in range(h):
            d.line([(0, y), (w, y)], fill=tuple(round(a[i] + (b[i] - a[i]) * y / h) for i in range(3)))
        shot = Image.open(os.path.join(raw, name)).convert('RGB')
        sw, sh = shot.size
        shot = shot.crop((0, round(sh * 0.036), sw, round(sh * 0.945)))
        k = min(880 / shot.width, 1580 / shot.height)
        shot = shot.resize((round(shot.width * k), round(shot.height * k)), Image.LANCZOS)
        mask = Image.new('L', shot.size, 0)
        ImageDraw.Draw(mask).rounded_rectangle([0, 0, shot.width - 1, shot.height - 1], radius=40, fill=255)
        canvas.paste(shot, ((w - shot.width) // 2, h - shot.height - 50), mask)
        caption = CAPTIONS.get(name[:2], '')
        d.multiline_text((w // 2, 145), caption, font=font, fill='white', anchor='mm', align='center', spacing=14)
        canvas.save(os.path.join(done, os.path.splitext(name)[0] + '.png'))
    return len(names)


print('screenshots:', screenshots())
